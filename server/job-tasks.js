import { analysisTaskId, parseTaskDeadline } from '../src/utils/tasks.js';

export async function tasksForJob(job, result) {
  if (!job.payload.resourceId) return [];
  const rows = [];
  for (const action of result.actionItems || []) {
    const parsed = parseTaskDeadline(action.deadline);
    if (/^\d{4}-\d{2}-\d{2}$/.test(action.deadline || '') && parsed.deadlineMs != null && job.payload.timeZone) {
      try {
        const target = Date.parse(action.deadline + 'T23:59:59.999Z');
        let epoch = target;
        const format = new Intl.DateTimeFormat('en-GB', { timeZone: job.payload.timeZone, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', second: '2-digit', hourCycle: 'h23' });
        for (let i = 0; i < 3; i++) {
          const parts = Object.fromEntries(format.formatToParts(epoch).map(part => [part.type, part.value]));
          const wall = Date.UTC(+parts.year, +parts.month - 1, +parts.day, +parts.hour, +parts.minute, +parts.second, 999);
          epoch += target - wall;
        }
        parsed.deadlineMs = epoch;
      } catch { /* Invalid time zones use the explicitly documented UTC fallback. */ }
    }
    rows.push({ id: await analysisTaskId(job.payload.resourceId, action.title), data: {
      title: action.title, description: action.description || '', category: result.category || 'General',
      status: 'todo', priority: 'Medium', ...parsed, bookmarked: false,
      sourceResourceId: job.payload.resourceId, autoGenerated: true,
    } });
  }
  return rows;
}
